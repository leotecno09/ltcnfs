#ifndef STORE_H
#define STORE_H

#include <stddef.h>

#define HASH_HEX_LEN 65 /* 64 hex characters with '\0' */

struct snapshot_report {
    unsigned long sr_files;
    unsigned long sr_dirs;
    unsigned long sr_skipped;
};

struct repo;

/*
    create, if not exists, root/ and root/objects/. 
    0 = ok, -1 = error
*/
int store_init(struct repo *r, const char *root);

/*
    save data[0... len) and writes in hash_hex the SHA-256 hash.
    If the objects already exists returns 0.
    0 = ok, -1 = error, 1 = already exists (deduplication)
*/
int store_put(const struct repo *r, const void *data, size_t len, char hash_hex[HASH_HEX_LEN]);

/*
    read the object. Allocates *data with malloc: the caller has to do free().
    0 = ok, -1 = error
*/
int store_get(const struct repo *r, const char *hash_hex, void **data, size_t *len);

/*
    returns 1 if the object exists, 0 if not.
*/
int store_exists(const struct repo *r, const char *hash_hex);

/*
    make a snapshot of path (it generates a tree as an object for the store)
    cascade_tree_hash is where to save the hash of a tree generated by the recursion of the function (the main caller will use it for making the commit)
    the sr struct is where to save a report of what the function did
    0 = ok, -1 = error
*/
int snapshot_dir(const struct repo *r, const char *path, char cascade_tree_hash[HASH_HEX_LEN], struct snapshot_report *sr);

/*
    make a commit (document me better pls)
*/
int commit(const struct repo *r, char tree_root_hash[HASH_HEX_LEN], const char *msg);
#endif